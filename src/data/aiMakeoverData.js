/**
 * Helper to retrieve photorealistic AI makeover concept
 */
export function getAIMakeoverDesign(roomType = "Master Bedroom", style = "Luxury", palette = "", variationIndex = 0) {
  // Normalize roomType
  let resolvedRoom = "Master Bedroom";
  if (roomType.includes("Living")) resolvedRoom = "Living Room";
  else if (roomType.includes("Kitchen")) resolvedRoom = "Modular Kitchen";
  else if (roomType.includes("Bath")) resolvedRoom = "Bathroom";
  else if (roomType.includes("Dining")) resolvedRoom = "Dining Room";
  else if (roomType.includes("Office")) resolvedRoom = "Home Office";
  else if (roomType.includes("Balcony")) resolvedRoom = "Balcony";

  const roomConfig = AI_MAKEOVER_CATALOG[resolvedRoom] || AI_MAKEOVER_CATALOG["Master Bedroom"];

  // Normalize style
  let resolvedStyle = "Luxury";
  if (roomConfig[style]) {
    resolvedStyle = style;
  } else if (style.toLowerCase().includes("japan") && roomConfig["Japandi"]) {
    resolvedStyle = "Japandi";
  } else if (style.toLowerCase().includes("minim") && roomConfig["Minimalist"]) {
    resolvedStyle = "Minimalist";
  } else if (style.toLowerCase().includes("classic") && roomConfig["Modern Classic"]) {
    resolvedStyle = "Modern Classic";
  } else if (roomConfig["Modern"]) {
    resolvedStyle = "Modern";
  }

  const design = roomConfig[resolvedStyle] || roomConfig["Luxury"] || Object.values(roomConfig)[0];
  const variations = design.variations || [design.image];
  const selectedImage = variations[variationIndex % variations.length] || design.image;

  return {
    roomType: resolvedRoom,
    style: resolvedStyle,
    image: selectedImage,
    variations,
    features: design.features,
    budget: design.budget,
    timeline: design.timeline,
    palette: palette || "Warm Beige & Champagne Gold"
  };
}

